def make_optimizer(lr: float, clip_value: float, weight_decay: float = 0.0, clip_type: str = "value"):
    """Optimizer used by both methods.

    The BMS GMM experiments report value gradient clipping at 1. We therefore
    default to elementwise value clipping. Global-norm clipping is still
    available for debugging via --grad_clip_type global_norm.
    """
    if clip_type == "value":
        clip = optax.clip(clip_value)
    elif clip_type == "global_norm":
        clip = optax.clip_by_global_norm(clip_value)
    else:
        raise ValueError(f"Unknown grad_clip_type={clip_type}")
    return optax.chain(clip, optax.adamw(lr, weight_decay=weight_decay))


