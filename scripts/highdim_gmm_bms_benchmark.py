def _np_logsumexp(a: np.ndarray, axis: int = -1, keepdims: bool = False) -> np.ndarray:
    m = np.max(a, axis=axis, keepdims=True)
    out = m + np.log(np.sum(np.exp(a - m), axis=axis, keepdims=True) + 1.0e-300)
    if not keepdims:
        out = np.squeeze(out, axis=axis)
    return out


def _kmeanspp_init(samples: np.ndarray, k: int, rng: np.random.Generator) -> np.ndarray:
    """Simple k-means++ initialization for post-hoc EM means."""
    n = samples.shape[0]
    means = np.empty((k, samples.shape[1]), dtype=np.float32)
    first = int(rng.integers(0, n))
    means[0] = samples[first]
    closest_d2 = np.sum((samples - means[0])**2, axis=1)
    for kk in range(1, k):
        total = float(np.sum(closest_d2))
        if not np.isfinite(total) or total <= 1.0e-12:
            idx = int(rng.integers(0, n))
        else:
            probs = closest_d2 / total
            idx = int(rng.choice(n, p=probs))
        means[kk] = samples[idx]
        d2 = np.sum((samples - means[kk])**2, axis=1)
        closest_d2 = np.minimum(closest_d2, d2)
    return means


def fit_diag_gmm_em(
    samples: np.ndarray,
    k: int,
    seed: int,
    n_iter: int,
    var_floor: float,
    chunk_size: int,
    init: str = "kmeanspp",
) -> Dict[str, np.ndarray]:
    """Fit a diagonal-covariance GMM by maximum likelihood EM.

    This is the post-hoc compression baseline:
        pure BMS samples -> K-component diagonal GMM by EM.

    The E-step is chunked to avoid materializing an (N,K,d) array for the full
    dataset at high dimension.
    """
    rng = np.random.default_rng(seed)
    x = np.asarray(samples, dtype=np.float32)
    finite_mask = np.all(np.isfinite(x), axis=1)
    if not np.all(finite_mask):
        x = x[finite_mask]
    n, dim = x.shape
    if n < k:
        raise ValueError(f"Need at least k finite samples for EM, got n={n}, k={k}")

    if init == "random":
        idx = rng.choice(n, size=k, replace=False)
        means = x[idx].copy()
    elif init == "kmeanspp":
        means = _kmeanspp_init(x, k, rng)
    else:
        raise ValueError(f"Unknown posthoc_gmm_init={init}")

    global_var = np.var(x, axis=0).astype(np.float32) + np.float32(var_floor)
    vars_ = np.tile(global_var[None, :], (k, 1)).astype(np.float32)
    weights = np.full((k,), 1.0 / k, dtype=np.float32)

    chunk_size = int(max(1, chunk_size))
    for _ in range(int(n_iter)):
        nk = np.zeros((k,), dtype=np.float64)
        sx = np.zeros((k, dim), dtype=np.float64)
        sx2 = np.zeros((k, dim), dtype=np.float64)

        log_det = np.sum(np.log(2.0 * np.pi * vars_), axis=1).astype(np.float32)
        log_weights = np.log(weights + 1.0e-30).astype(np.float32)

        for start in range(0, n, chunk_size):
            xb = x[start:start + chunk_size]
            # Shape (B,K,d). Keep B modest using chunk_size.
            diff = xb[:, None, :] - means[None, :, :]
            quad = np.sum((diff * diff) / vars_[None, :, :], axis=2)
            log_comp = log_weights[None, :] - 0.5 * (quad + log_det[None, :])
            lse = _np_logsumexp(log_comp, axis=1, keepdims=True)
            resp = np.exp(log_comp - lse).astype(np.float64)

            nk += np.sum(resp, axis=0)
            sx += resp.T @ xb.astype(np.float64)
            sx2 += resp.T @ (xb.astype(np.float64)**2)

        nk_safe = np.maximum(nk, 1.0e-8)
        weights = (nk_safe / float(n)).astype(np.float32)
        means = (sx / nk_safe[:, None]).astype(np.float32)
        vars_new = sx2 / nk_safe[:, None] - means.astype(np.float64)**2
        vars_ = np.maximum(vars_new, float(var_floor)).astype(np.float32)
        weights = np.nan_to_num(weights, nan=0.0, posinf=0.0, neginf=0.0)
        weights = np.maximum(weights, 0.0)
        weight_sum = float(np.sum(weights))
        if (not np.isfinite(weight_sum)) or weight_sum <= 0.0:
            weights = np.full((k,), 1.0 / k, dtype=np.float32)
        else:
            weights = (weights / weight_sum).astype(np.float32)
        means = np.nan_to_num(means, nan=0.0, posinf=1.0e6, neginf=-1.0e6).astype(np.float32)
        vars_ = np.nan_to_num(vars_, nan=float(var_floor), posinf=1.0e6, neginf=float(var_floor)).astype(np.float32)
        vars_ = np.maximum(vars_, float(var_floor)).astype(np.float32)

    return {"weights": weights, "means": means, "vars": vars_}


def sample_np_diag_gmm(gmm: Dict[str, np.ndarray], seed: int, n: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    weights = np.asarray(gmm["weights"], dtype=np.float64)
    weights = np.nan_to_num(weights, nan=0.0, posinf=0.0, neginf=0.0)
    weights = np.maximum(weights, 0.0)
    wsum = float(weights.sum())
    if (not np.isfinite(wsum)) or wsum <= 0.0:
        weights = np.full_like(weights, 1.0 / len(weights), dtype=np.float64)
    else:
        weights = weights / wsum
    means = np.asarray(gmm["means"], dtype=np.float32)
    vars_ = np.asarray(gmm["vars"], dtype=np.float32)
    means = np.nan_to_num(means, nan=0.0, posinf=1.0e6, neginf=-1.0e6)
    vars_ = np.nan_to_num(vars_, nan=1.0, posinf=1.0e6, neginf=1.0)
    vars_ = np.maximum(vars_, 1.0e-8)
    comp = rng.choice(means.shape[0], size=n, p=weights)
    eps = rng.normal(size=(n, means.shape[1])).astype(np.float32)
    return means[comp] + np.sqrt(vars_[comp]) * eps


def sample_pure_bms_np_batched(args, state, key, n_samples: int) -> np.ndarray:
    """Generate pure-BMS endpoint samples in batches for post-hoc fitting."""
    outs = []
    remaining = int(n_samples)
    batch = int(max(1, args.posthoc_sample_batch))
    while remaining > 0:
        n = min(batch, remaining)
        key, sub = jax.random.split(key)
        key_x0, key_sde = jax.random.split(sub)
        x0 = jnp.sqrt(args.prior_var) * jax.random.normal(key_x0, (n, args.current_dim), dtype=jnp.float32)
        xT = simulate_sde(state.apply_fn, state.params, x0, key_sde, args.sigma, args.sde_steps, args.state_clip,
                          args.control_clip)
        outs.append(np.asarray(jax.device_get(xT), dtype=np.float32))
        remaining -= n
    return np.concatenate(outs, axis=0)


def train_pure_bms_posthoc_gmm(args, key, target_means):
    """Train pure BMS, then fit a post-hoc diagonal GMM to its endpoint samples."""
    key_bms, key_fit, key_em = jax.random.split(key, 3)
    bms_state, train_info = train_pure_bms(args, key_bms, target_means)

    t0 = time.time()
    fit_samples = sample_pure_bms_np_batched(args, bms_state, key_fit, args.posthoc_fit_samples)
    gmm = fit_diag_gmm_em(
        fit_samples,
        k=args.learned_components,
        seed=int(jax.random.randint(key_em, (), 0, 2**31 - 1)),
        n_iter=args.posthoc_em_iters,
        var_floor=args.posthoc_var_floor,
        chunk_size=args.posthoc_em_chunk,
        init=args.posthoc_gmm_init,
    )
    em_time = time.time() - t0
    info = dict(train_info)
    info.update({
        "posthoc_fit_samples": int(args.posthoc_fit_samples),
        "posthoc_components": int(args.learned_components),
        "posthoc_em_iters": int(args.posthoc_em_iters),
        "posthoc_em_time_sec": float(em_time),
        "posthoc_total_time_sec": float(train_info.get("train_time_sec", 0.0) + em_time),
        "posthoc_sde_nfes": int(args.posthoc_fit_samples) * int(args.sde_steps),
        "total_sde_nfes": int(info.get("train_sde_nfes", 0)) + int(args.posthoc_fit_samples) * int(args.sde_steps),
    })
    return {"bms_state": bms_state, "posthoc_gmm": gmm}, info


def sample_method(args, method: str, state, key) -> jnp.ndarray:
    if method == "gmm_bms":
        return sample_terminal_gmm(state.params, key, args.eval_samples, args.var_floor)
    if method == "pure_bms":
        key_x0, key_sde = jax.random.split(key)
        x0 = jnp.sqrt(args.prior_var) * jax.random.normal(key_x0, (args.eval_samples, args.current_dim))
        return simulate_sde(state.apply_fn, state.params, x0, key_sde, args.sigma, args.sde_steps, args.state_clip,
                            args.control_clip)
    if method == "pure_bms_posthoc_gmm":
        # Evaluate the explicit GMM fitted to pure-BMS endpoint samples.
        samples = sample_np_diag_gmm(state["posthoc_gmm"],
                                     seed=int(jax.random.randint(key, (), 0, 2**31 - 1)),
                                     n=args.eval_samples)
        return jnp.asarray(samples)
    raise ValueError(method)


def evaluate_samples(args, samples: jnp.ndarray, target_samples: jnp.ndarray, target_means: jnp.ndarray,
                     seed: int) -> Dict[str, float]:
    xs = np.asarray(jax.device_get(samples))
    ys = np.asarray(jax.device_get(target_samples))
    mus = np.asarray(jax.device_get(target_means))
    true_weights = np.ones(mus.shape[0]) / mus.shape[0]
    w2_n = min(args.w2_samples, xs.shape[0], ys.shape[0])
    return {
        "mode_tvd": mode_tvd(xs, mus, true_weights),
        "sliced_tvd": sliced_tvd(xs, ys, args.sliced_projections, args.sliced_bins, seed),
        "w2": sample_w2(xs[:w2_n], ys[:w2_n]) if not args.skip_w2 else float("nan"),
    }


def write_csv(path: Path, rows: List[Dict[str, object]]) -> None:
    if not rows:
        return
    # Different methods have method-specific diagnostics, so use the union of
    # keys rather than the first row's keys. This avoids dropping/raising on
    # post-hoc EM diagnostics when mixed with GMM-BMS rows.
    preferred = [
        "method",
        "dim",
        "seed",
        "target_modes",
        "mode_scale",
        "sigma",
        "eta",
        "steps",
        "outer_every",
        "batch_size",
        "importance_weights",
        "mode_tvd",
        "sliced_tvd",
        "w2",
        "train_sde_nfes",
        "target_score_evals",
        "target_density_evals",
    ]
    all_keys = []
    seen = set()
    for k in preferred:
        if any(k in r for r in rows):
            all_keys.append(k)
            seen.add(k)
    for r in rows:
        for k in r.keys():
            if k not in seen:
                all_keys.append(k)
                seen.add(k)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_keys, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: List[Dict[str, object]]) -> List[Dict[str, object]]:
    groups: Dict[Tuple[str, int, float], List[Dict[str, object]]] = {}
    for r in rows:
        groups.setdefault((str(r["method"]), int(r["dim"]), float(r.get("eta", 0.0))), []).append(r)
    out = []
    metrics = ["mode_tvd", "sliced_tvd", "w2"]
    for (method, dim, eta), rs in sorted(groups.items(), key=lambda x: (x[0][1], x[0][0], x[0][2])):
        row: Dict[str, object] = {"method": method, "dim": dim, "eta": eta, "n_seeds": len(rs)}
        for m in metrics:
            vals = np.asarray([float(r[m]) for r in rs], dtype=np.float64)
            row[f"{m}_mean"] = float(np.nanmean(vals))
            row[f"{m}_std"] = float(np.nanstd(vals, ddof=1)) if len(vals) > 1 else 0.0
        out.append(row)
    return out


def plot_summary(summary_rows: List[Dict[str, object]], out_dir: Path) -> None:
    if not summary_rows:
        return
    metrics = ["mode_tvd", "sliced_tvd", "w2"]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4), constrained_layout=True)
    labels = sorted(set((str(r["method"]), float(r.get("eta", 0.0))) for r in summary_rows))
    for ax, metric in zip(axes, metrics):
        for method, eta in labels:
            rs = [r for r in summary_rows if r["method"] == method and float(r.get("eta", 0.0)) == eta]
            rs = sorted(rs, key=lambda r: int(r["dim"]))
            dims = [int(r["dim"]) for r in rs]
            means = [float(r[f"{metric}_mean"]) for r in rs]
            stds = [float(r[f"{metric}_std"]) for r in rs]
            label = f"{method} η={eta:g}"
            ax.errorbar(dims, means, yerr=stds, marker="o", label=label)
        ax.set_xscale("log")
        ax.set_xlabel("dimension d")
        ax.set_ylabel(metric + " ↓")
        ax.set_title(metric)
        ax.grid(True, alpha=0.25)
    axes[0].legend()
    fig.savefig(out_dir / "metric_vs_dim.png", dpi=200)
    plt.close(fig)


