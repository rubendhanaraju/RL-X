def _mode_assign_numpy(samples: np.ndarray, means: np.ndarray, batch: int = 2048) -> np.ndarray:
    assigns = []
    for i in range(0, samples.shape[0], batch):
        x = samples[i:i + batch]
        # Equal weights and unit/isotropic covariance => nearest target component.
        dist2 = ((x[:, None, :] - means[None, :, :])**2).sum(axis=-1)
        assigns.append(np.argmin(dist2, axis=1))
    return np.concatenate(assigns, axis=0)


def mode_tvd(samples: np.ndarray, means: np.ndarray, true_weights: np.ndarray) -> float:
    assign = _mode_assign_numpy(samples, means)
    counts = np.bincount(assign, minlength=means.shape[0]).astype(np.float64)
    emp = counts / max(1.0, counts.sum())
    # Conventional TVD = 0.5 ||p-q||_1. The paper's displayed equation omits
    # 1/2 but states mode TVD in [0,1], so we use conventional TVD.
    return float(0.5 * np.abs(emp - true_weights).sum())


def sliced_tvd(
    model_samples: np.ndarray,
    target_samples: np.ndarray,
    n_proj: int,
    n_bins: int,
    seed: int,
) -> float:
    rng = np.random.default_rng(seed)
    dim = model_samples.shape[1]
    dirs = rng.normal(size=(n_proj, dim))
    dirs /= np.linalg.norm(dirs, axis=1, keepdims=True) + 1.0e-12
    xm = model_samples @ dirs.T
    xt = target_samples @ dirs.T
    vals = []
    for p in range(n_proj):
        a = xm[:, p]
        b = xt[:, p]
        lo = min(a.min(), b.min())
        hi = max(a.max(), b.max())
        if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo:
            vals.append(0.0)
            continue
        ha, _ = np.histogram(a, bins=n_bins, range=(lo, hi), density=False)
        hb, _ = np.histogram(b, bins=n_bins, range=(lo, hi), density=False)
        pa = ha.astype(np.float64) / max(1.0, ha.sum())
        pb = hb.astype(np.float64) / max(1.0, hb.sum())
        vals.append(0.5 * np.abs(pa - pb).sum())
    return float(np.mean(vals))


def sample_w2(model_samples: np.ndarray, target_samples: np.ndarray) -> float:
    """Equal-weight empirical W2 with squared Euclidean cost.

    Prefer POT if installed. Fallback uses scipy linear_sum_assignment, which is
    exact for equal-size equal-weight samples but can be slow for large n.
    """
    n = min(model_samples.shape[0], target_samples.shape[0])
    x = np.asarray(model_samples[:n], dtype=np.float64)
    y = np.asarray(target_samples[:n], dtype=np.float64)
    try:
        import ot  # type: ignore

        a = np.ones(n, dtype=np.float64) / n
        b = np.ones(n, dtype=np.float64) / n
        M = ot.dist(x, y, metric="sqeuclidean")
        val = ot.emd2(a, b, M, numItermax=1_000_000)
        return float(np.sqrt(max(0.0, val)))
    except Exception:
        try:
            from scipy.optimize import linear_sum_assignment

            x2 = np.sum(x * x, axis=1, keepdims=True)
            y2 = np.sum(y * y, axis=1, keepdims=True).T
            M = x2 + y2 - 2.0 * (x @ y.T)
            rows, cols = linear_sum_assignment(M)
            return float(np.sqrt(max(0.0, M[rows, cols].mean())))
        except Exception:
            return float("nan")


