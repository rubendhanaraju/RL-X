def parse_int_list(s: str) -> List[int]:
    return [int(x) for x in s.split(",") if x.strip()]


def parse_float_list(s: str) -> List[float]:
    return [float(x) for x in s.split(",") if x.strip()]


def parse_methods(s: str) -> List[str]:
    methods = [x.strip() for x in s.split(",") if x.strip()]
    valid = {"gmm_bms", "pure_bms", "pure_bms_posthoc_gmm"}
    bad = [m for m in methods if m not in valid]
    if bad:
        raise ValueError(f"Unknown methods {bad}; valid={valid}")
    return methods


