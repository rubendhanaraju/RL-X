def main():
    args = parse_args()
    args.dims_list = parse_int_list(args.dims)
    args.seeds_list = parse_int_list(args.seeds)
    args.methods_list = parse_methods(args.methods)
    args.etas_list = parse_float_list(args.etas) if args.etas is not None else [float(args.eta)]
    args.prior_var = float(args.prior_std**2)

    if args.paper_train_schedule:
        args.outer_steps = 1000
        args.grad_steps_per_outer = 1000
    if args.outer_steps is not None or args.grad_steps_per_outer is not None:
        if args.outer_steps is None or args.grad_steps_per_outer is None:
            raise ValueError("Set both --outer_steps and --grad_steps_per_outer, or neither.")
        args.steps = int(args.outer_steps) * int(args.grad_steps_per_outer)
        args.outer_every = int(args.grad_steps_per_outer)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "config.json").open("w") as f:
        json.dump({k: (str(v) if isinstance(v, Path) else v) for k, v in vars(args).items()}, f, indent=2)

    print("JAX devices:", jax.devices())
    print("Output:", out_dir)
    print("Methods:", args.methods_list)
    print("Dims:", args.dims_list, "Seeds:", args.seeds_list, "Etas:", args.etas_list)
    print(f"Training schedule: steps={args.steps}, outer_every={args.outer_every}, batch_size={args.batch_size}")

    rows: List[Dict[str, object]] = []
    for dim in args.dims_list:
        args.current_dim = int(dim)
        for seed in args.seeds_list:
            base_key = jax.random.PRNGKey(seed)
            key_target, key_train, key_eval, key_target_eval = jax.random.split(base_key, 4)
            target_means = make_target_means(key_target, dim, args.target_modes, args.mode_scale)
            target_samples = sample_target_gmm(key_target_eval, target_means, args.eval_samples, args.target_var)

            for eta_value in args.etas_list:
                args.eta = float(eta_value)
                for method in args.methods_list:
                    print("=" * 80)
                    print(f"Running method={method} dim={dim} seed={seed} eta={args.eta}")
                    key_train, key_method, key_sample = jax.random.split(key_train, 3)
                    if method == "gmm_bms":
                        state, train_info = train_gmm_bms(args, key_method, target_means)
                    elif method == "pure_bms":
                        state, train_info = train_pure_bms(args, key_method, target_means)
                    elif method == "pure_bms_posthoc_gmm":
                        state, train_info = train_pure_bms_posthoc_gmm(args, key_method, target_means)
                    else:
                        raise ValueError(method)

                    samples = sample_method(args, method, state, key_sample)
                    eval_info = evaluate_samples(args, samples, target_samples, target_means, seed + 17)
                    row: Dict[str, object] = {
                        "method": method,
                        "dim": dim,
                        "seed": seed,
                        "target_modes": args.target_modes,
                        "mode_scale": args.mode_scale,
                        "sigma": args.sigma,
                        "eta": args.eta,
                        "steps": args.steps,
                        "outer_every": args.outer_every,
                        "batch_size": args.batch_size,
                        "importance_weights": bool(args.use_importance_weights) if method == "gmm_bms" else False,
                    }
                    row.update(train_info)
                    row.update(eval_info)
                    rows.append(row)
                    print("RESULT", row)
                    write_csv(out_dir / "per_run_results.csv", rows)
                    summary_rows = summarize(rows)
                    write_csv(out_dir / "summary_results.csv", summary_rows)
                    plot_summary(summary_rows, out_dir)

    summary_rows = summarize(rows)
    write_csv(out_dir / "summary_results.csv", summary_rows)
    plot_summary(summary_rows, out_dir)
    print("Done.")
    print("Per-run results:", out_dir / "per_run_results.csv")
    print("Summary results:", out_dir / "summary_results.csv")
    print("Plot:", out_dir / "metric_vs_dim.png")


if __name__ == "__main__":
    main()
