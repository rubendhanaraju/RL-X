# -----------------------------------------------------------------------------
# Numerical safety utilities
# -----------------------------------------------------------------------------


def safe_array(x: jnp.ndarray, clip: float) -> jnp.ndarray:
    """Replace non-finite values and optionally clip coordinates.

    This is intentionally inactive for ordinary finite values when clip is large.
    It prevents a single unstable SDE rollout from poisoning a replay buffer or
    post-hoc EM fit with NaNs/Infs.
    """
    clip = jnp.asarray(clip, dtype=x.dtype)
    x = jnp.nan_to_num(x, nan=0.0, posinf=clip, neginf=-clip)
    return jnp.clip(x, -clip, clip)


def clip_vector_norm(x: jnp.ndarray, max_norm: float) -> jnp.ndarray:
    """Per-sample vector norm clipping. If max_norm <= 0, do nothing."""
    max_norm = jnp.asarray(max_norm, dtype=x.dtype)
    norm = jnp.linalg.norm(x, axis=-1, keepdims=True)
    scale = jnp.minimum(1.0, max_norm / (norm + 1.0e-6))
    return jnp.where(max_norm > 0.0, x * scale, x)


def apply_gradients_if_finite(state: train_state.TrainState, grads, loss: jnp.ndarray):
    """Apply an update only if loss and gradients are finite."""
    leaves = jax.tree_util.tree_leaves(grads)
    finite = jnp.isfinite(loss)
    for g in leaves:
        finite = jnp.logical_and(finite, jnp.all(jnp.isfinite(g)))
    clean_grads = jax.tree_util.tree_map(lambda g: jnp.nan_to_num(g, nan=0.0, posinf=0.0, neginf=0.0), grads)
    new_state = state.apply_gradients(grads=clean_grads)
    state = jax.lax.cond(finite, lambda _: new_state, lambda _: state, operand=None)
    return state, finite


def safe_metric_dict(metrics: Dict[str, jnp.ndarray]) -> Dict[str, jnp.ndarray]:
    return {k: jnp.nan_to_num(v, nan=jnp.inf, posinf=jnp.inf, neginf=-jnp.inf) for k, v in metrics.items()}


