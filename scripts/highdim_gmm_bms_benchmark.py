def train_pure_bms(args, key, target_means):
    model = FourierTimeMLP(
        dim=args.current_dim,
        hidden=args.bms_hidden,
        depth=args.bms_depth,
        time_features=args.time_features,
        x_scale=max(1.0, args.mode_scale),
        output_scale=args.bms_output_scale,
        control_clip=args.control_clip,
    )
    key_init, key_loop = jax.random.split(key)
    variables = model.init(
        key_init,
        jnp.zeros((4, args.current_dim), dtype=jnp.float32),
        jnp.ones((4,), dtype=jnp.float32) * 0.5,
        args.sigma,
    )
    state = train_state.TrainState.create(
        apply_fn=model.apply,
        params=variables["params"],
        tx=make_optimizer(args.lr_bms, args.grad_clip, clip_type=args.grad_clip_type),
    )

    ref_params = state.params
    t0 = time.time()
    last = {}
    endpoint_simulations = 0

    # More faithful BMS baseline: maintain a replay buffer of terminal endpoints
    # X_T generated by the current drift. For BMS, the regression coupling is
    # P_0^{u_i} ⊗ P_T^{u_i}: X_T comes from this buffer, while X_0 is
    # resampled independently from the prior inside train_step_pure_bms_buffered.
    use_replay = bool(args.pure_bms_replay)
    if use_replay:
        buffer_size = int(args.buffer_size)
        refresh_chunk = int(max(1, min(args.buffer_refresh_samples, buffer_size)))
        buffer_x0 = jnp.zeros((buffer_size, args.current_dim),
                              dtype=jnp.float32)  # kept for API/backward compatibility; unused by BMS coupling
        buffer_xT = jnp.zeros((buffer_size, args.current_dim), dtype=jnp.float32)
        buffer_ptr = 0
        valid_count = 0

        def refresh_buffer_chunk(key_refresh, buffer_x0, buffer_xT, buffer_ptr, valid_count, n_refresh):
            new_x0, new_xT = simulate_endpoint_batch(
                state.apply_fn,
                state.params,
                key_refresh,
                int(n_refresh),
                args.current_dim,
                args.prior_var,
                args.sigma,
                args.sde_steps,
                args.state_clip,
                args.control_clip,
            )
            idx = (jnp.arange(int(n_refresh)) + int(buffer_ptr)) % buffer_size
            buffer_x0 = buffer_x0.at[idx].set(new_x0)
            buffer_xT = buffer_xT.at[idx].set(new_xT)
            buffer_ptr = (int(buffer_ptr) + int(n_refresh)) % buffer_size
            valid_count = min(buffer_size, int(valid_count) + int(n_refresh))
            return buffer_x0, buffer_xT, buffer_ptr, valid_count

        def refresh_buffer_outer(key_refresh, buffer_x0, buffer_xT, buffer_ptr, valid_count):
            # Paper-style: simulate a full buffer for each outer iteration.
            # Debug-style: simulate only buffer_refresh_samples and use a ring buffer.
            total_new = buffer_size if bool(args.full_buffer_refresh) else refresh_chunk
            if bool(args.full_buffer_refresh):
                buffer_ptr = 0
                valid_count = 0
            produced = 0
            nonlocal_endpoint_simulations = 0
            while produced < total_new:
                n_now = min(refresh_chunk, total_new - produced)
                key_refresh, sub_refresh = jax.random.split(key_refresh)
                buffer_x0, buffer_xT, buffer_ptr, valid_count = refresh_buffer_chunk(
                    sub_refresh, buffer_x0, buffer_xT, buffer_ptr, valid_count, n_now)
                produced += n_now
                nonlocal_endpoint_simulations += n_now
            return buffer_x0, buffer_xT, buffer_ptr, valid_count, nonlocal_endpoint_simulations

        # No warmup is needed for the default loop because step 1 refreshes before
        # the first gradient update. Keep optional warmup for users who disable
        # refresh-at-step-one in custom edits.
        warmup_batches = max(0, int(args.buffer_warmup_batches))
        for _ in range(warmup_batches):
            key_loop, sub = jax.random.split(key_loop)
            buffer_x0, buffer_xT, buffer_ptr, valid_count = refresh_buffer_chunk(sub, buffer_x0, buffer_xT, buffer_ptr,
                                                                                 valid_count, refresh_chunk)
            endpoint_simulations += refresh_chunk

    for step in range(1, args.steps + 1):
        key_loop, sub = jax.random.split(key_loop)
        if (step - 1) % args.outer_every == 0:
            ref_params = jax.tree_util.tree_map(lambda z: z, state.params)
            if use_replay:
                # Refresh endpoint coupling under the current drift at the same
                # cadence as the damped fixed-point reference update. With
                # --full_buffer_refresh this matches Algorithm 2's fresh buffer
                # per outer iteration; otherwise it updates a ring buffer chunk.
                buffer_x0, buffer_xT, buffer_ptr, valid_count, n_sim = refresh_buffer_outer(
                    sub, buffer_x0, buffer_xT, buffer_ptr, valid_count)
                endpoint_simulations += int(n_sim)
                key_loop, sub = jax.random.split(key_loop)

        if use_replay:
            state, metrics = train_step_pure_bms_buffered(
                state,
                ref_params,
                sub,
                buffer_x0,
                buffer_xT,
                jnp.asarray(valid_count, dtype=jnp.int32),
                args.batch_size,
                args.sigma,
                args.t_eps,
                args.prior_var,
                args.eta,
                target_means,
                args.target_var,
                args.state_clip,
                args.control_clip,
                args.xi_clip,
            )
        else:
            state, metrics = train_step_pure_bms(
                state,
                ref_params,
                sub,
                args.batch_size,
                args.sigma,
                args.t_eps,
                args.prior_var,
                args.eta,
                target_means,
                args.target_var,
                args.sde_steps,
                args.state_clip,
                args.control_clip,
                args.xi_clip,
            )
            endpoint_simulations += args.batch_size

        if step == 1 or step % args.log_every == 0 or step == args.steps:
            last = jax.device_get(metrics)
            extra = f" buffer={valid_count}" if use_replay else " online"
            print(f"[pure_bms d={args.current_dim} step={step:6d}] "
                  f"loss={float(last['loss']):.4f} mse={float(last['drift_mse']):.4f} "
                  f"damp={float(last['damping']):.4f} finite={bool(last.get('update_finite', True))}{extra}")

    return state, {
        "train_time_sec": time.time() - t0,
        "replay_buffer_used": bool(use_replay),
        "endpoint_simulations": int(endpoint_simulations),
        "train_sde_nfes": int(endpoint_simulations) * int(args.sde_steps),
        "target_score_evals": int(args.steps) * int(args.batch_size),
        "target_density_evals": 0,
        **{
            k: float(v) for k, v in last.items()
        },
    }


