@dataclass
class TargetSpec:
    dim: int
    modes: int
    mode_scale: float
    target_var: float
    seed: int


def make_target_means(key, dim: int, modes: int, mode_scale: float) -> jnp.ndarray:
    return jax.random.uniform(key, (modes, dim), minval=-mode_scale, maxval=mode_scale)


def target_log_rho_unit_gmm(x: jnp.ndarray, means: jnp.ndarray, target_var: float) -> jnp.ndarray:
    """Unnormalized log density of equally weighted isotropic GMM.

    Constants independent of x are omitted. This is OK for scores and for
    self-normalized endpoint importance weights.

    x: (batch, d), means: (K, d)
    """
    diff = x[:, None, :] - means[None, :, :]
    quad = jnp.sum(diff * diff, axis=-1) / target_var
    return jax.nn.logsumexp(-0.5 * quad, axis=-1) - jnp.log(means.shape[0])


def target_score_unit_gmm(x: jnp.ndarray, means: jnp.ndarray, target_var: float) -> jnp.ndarray:
    """Score grad_x log rho(x) for equally weighted isotropic GMM."""
    diff = x[:, None, :] - means[None, :, :]
    quad = jnp.sum(diff * diff, axis=-1) / target_var
    resp = jax.nn.softmax(-0.5 * quad, axis=-1)
    comp_scores = -diff / target_var
    return jnp.sum(resp[:, :, None] * comp_scores, axis=1)


def sample_target_gmm(key, means: jnp.ndarray, n: int, target_var: float) -> jnp.ndarray:
    key_c, key_eps = jax.random.split(key)
    comp = jax.random.randint(key_c, (n,), minval=0, maxval=means.shape[0])
    eps = jax.random.normal(key_eps, (n, means.shape[1]))
    return means[comp] + jnp.sqrt(target_var) * eps


# -----------------------------------------------------------------------------
# Common BMS bridge target
# -----------------------------------------------------------------------------


def sample_brownian_bridge(x0: jnp.ndarray, xT: jnp.ndarray, t: jnp.ndarray, key, sigma: float) -> jnp.ndarray:
    tc = t[:, None]
    mean = (1.0 - tc) * x0 + tc * xT
    std = sigma * jnp.sqrt(tc * (1.0 - tc))
    return mean + std * jax.random.normal(key, x0.shape)


def bms_independent_target_control(
    x0: jnp.ndarray,
    xT: jnp.ndarray,
    xt: jnp.ndarray,
    t: jnp.ndarray,
    sigma: float,
    prior_var: float,
    target_means: jnp.ndarray,
    target_var: float,
) -> jnp.ndarray:
    """Independent-coupling BMS target with c(t)=gamma(t)=t, T=1.

    sigma^{-1} xi = grad_x0 log p0(x0)
                    + grad_xT log p_target(xT)
                    - grad_xt log P_{t|0}(xt | x0)

    For Brownian reference P_{t|0}=N(x0, sigma^2 t I), so the last score is
    -(xt-x0)/(sigma^2 t).
    """
    tc = t[:, None]
    prior_score = -x0 / prior_var
    terminal_score = target_score_unit_gmm(xT, target_means, target_var)
    grad_log_pt_given_0 = -(xt - x0) / (sigma**2 * tc)
    return sigma * (prior_score + terminal_score - grad_log_pt_given_0)


