class FourierTimeMLP(nn.Module):
    """Residual Fourier-time MLP used for the pure/regular BMS baseline.

    The BMS paper reports a residual network with 6 layers, 512 hidden units,
    and Fourier time embeddings for the GMM experiments. This module implements
    that style: x is scaled by the target support, t is Fourier-embedded, the
    concatenated input is projected to hidden dimension, and then passed through
    residual MLP blocks before a small-initialized vector-field head.
    """

    dim: int
    hidden: int
    depth: int
    time_features: int
    x_scale: float
    output_scale: float = 1.0
    control_clip: float = 0.0

    @nn.compact
    def __call__(self, x: jnp.ndarray, t: jnp.ndarray, sigma: float) -> jnp.ndarray:
        del sigma
        freqs = jnp.asarray(2.0**jnp.arange(self.time_features), dtype=x.dtype) * jnp.pi
        angles = t[:, None] * freqs[None, :]
        tf = jnp.concatenate([t[:, None], jnp.sin(angles), jnp.cos(angles)], axis=-1)
        h = jnp.concatenate([x / self.x_scale, tf], axis=-1)
        h = nn.Dense(self.hidden)(h)
        h = nn.silu(h)
        for _ in range(self.depth):
            residual = h
            z = nn.Dense(self.hidden)(h)
            z = nn.silu(z)
            z = nn.Dense(self.hidden)(z)
            # Keep residual variance controlled across many blocks.
            h = (residual + z) / jnp.sqrt(jnp.asarray(2.0, dtype=h.dtype))
            h = nn.silu(h)
        out = nn.Dense(self.dim, kernel_init=nn.initializers.normal(1.0e-3))(h)
        out = self.output_scale * out
        return clip_vector_norm(safe_array(out, 1.0e6), self.control_clip)


@partial(jax.jit, static_argnames=("apply_fn", "n_steps"))
def simulate_sde(
    apply_fn,
    params,
    x0: jnp.ndarray,
    key,
    sigma: float,
    n_steps: int,
    state_clip: float,
    control_clip: float,
) -> jnp.ndarray:
    dt = 1.0 / float(n_steps)
    sqrt_dt = jnp.sqrt(dt)
    keys = jax.random.split(key, n_steps)
    ts = jnp.linspace(0.0, 1.0 - dt, n_steps)

    def body(x, inp):
        kk, tt = inp
        tb = jnp.full((x.shape[0],), tt, dtype=x.dtype)
        x = safe_array(x, state_clip)
        u = apply_fn({"params": params}, x, tb, sigma)
        u = clip_vector_norm(safe_array(u, state_clip), control_clip)
        noise = jax.random.normal(kk, x.shape)
        x_next = x + sigma * u * dt + sigma * sqrt_dt * noise
        x_next = safe_array(x_next, state_clip)
        return x_next, None

    x0 = safe_array(x0, state_clip)
    xT, _ = jax.lax.scan(body, x0, (keys, ts))
    return safe_array(xT, state_clip)


@partial(jax.jit, static_argnames=("batch_size", "n_sde_steps"))
def train_step_pure_bms(
    state: train_state.TrainState,
    ref_params,
    key,
    batch_size: int,
    sigma: float,
    t_eps: float,
    prior_var: float,
    eta: float,
    target_means: jnp.ndarray,
    target_var: float,
    n_sde_steps: int,
    state_clip: float,
    control_clip: float,
    xi_clip: float,
):
    key_x0_sim, key_sde, key_x0_bridge, key_t, key_bridge = jax.random.split(key, 5)
    # Simulate terminal endpoints from the current model: X_T ~ P_T^{u_i}.
    # For BMS, the coupling is independent, P_0^{u_i} ⊗ P_T^{u_i}; therefore
    # the X_0 used in the Brownian bridge regression is resampled independently
    # from the prior rather than paired with the trajectory that produced X_T.
    x0_sim = jnp.sqrt(prior_var) * jax.random.normal(key_x0_sim, (batch_size, target_means.shape[1]))
    xT = simulate_sde(state.apply_fn, state.params, x0_sim, key_sde, sigma, n_sde_steps, state_clip, control_clip)
    xT = jax.lax.stop_gradient(xT)
    x0 = jnp.sqrt(prior_var) * jax.random.normal(key_x0_bridge, (batch_size, target_means.shape[1]))
    t = jax.random.uniform(key_t, (batch_size,), minval=t_eps, maxval=1.0 - t_eps)
    xt = sample_brownian_bridge(x0, xT, t, key_bridge, sigma)

    xi = bms_independent_target_control(x0, xT, xt, t, sigma, prior_var, target_means, target_var)
    xi = clip_vector_norm(safe_array(xi, state_clip), xi_clip)
    xi = jax.lax.stop_gradient(xi)
    u_ref = state.apply_fn({"params": ref_params}, xt, t, sigma)
    u_ref = clip_vector_norm(safe_array(u_ref, state_clip), control_clip)
    u_ref = jax.lax.stop_gradient(u_ref)

    def loss_fn(params):
        u_pred = state.apply_fn({"params": params}, xt, t, sigma)
        u_pred = clip_vector_norm(safe_array(u_pred, state_clip), control_clip)
        drift_mse = 0.5 * jnp.mean(jnp.sum((u_pred - xi)**2, axis=-1))
        damping = 0.5 * eta * jnp.mean(jnp.sum((u_pred - u_ref)**2, axis=-1))
        total = drift_mse + damping
        return total, {"loss": total, "drift_mse": drift_mse, "damping": damping}

    (loss, metrics), grads = jax.value_and_grad(loss_fn, has_aux=True)(state.params)
    state, update_finite = apply_gradients_if_finite(state, grads, loss)
    metrics = safe_metric_dict(metrics)
    metrics["update_finite"] = update_finite
    return state, metrics


@partial(jax.jit, static_argnames=("apply_fn", "n_samples", "dim", "n_sde_steps"))
def simulate_endpoint_batch(
    apply_fn,
    params,
    key,
    n_samples: int,
    dim: int,
    prior_var: float,
    sigma: float,
    n_sde_steps: int,
    state_clip: float,
    control_clip: float,
) -> Tuple[jnp.ndarray, jnp.ndarray]:
    """Simulate endpoint pairs (X_0, X_T) for the current pure-BMS drift.

    This is the simulation/coupling part of BMS. Keeping it separate from the
    gradient step lets the pure-BMS baseline use a replay endpoint buffer, which
    is closer to the BMS paper's practical Algorithm 2 than resimulating every
    mini-batch from scratch.
    """
    key_x0, key_sde = jax.random.split(key)
    x0 = jnp.sqrt(prior_var) * jax.random.normal(key_x0, (n_samples, dim))
    xT = simulate_sde(apply_fn, params, x0, key_sde, sigma, n_sde_steps, state_clip, control_clip)
    return x0, xT


@partial(jax.jit, static_argnames=("batch_size",))
def train_step_pure_bms_buffered(
    state: train_state.TrainState,
    ref_params,
    key,
    buffer_x0: jnp.ndarray,
    buffer_xT: jnp.ndarray,
    valid_count: jnp.ndarray,
    batch_size: int,
    sigma: float,
    t_eps: float,
    prior_var: float,
    eta: float,
    target_means: jnp.ndarray,
    target_var: float,
    state_clip: float,
    control_clip: float,
    xi_clip: float,
):
    """Pure-BMS Markovianization step using an endpoint replay buffer.

    For true BMS, the coupling is independent: X_0 is drawn from the prior and
    X_T is drawn from the current model terminal law. Thus the buffer supplies
    terminal endpoints only; the initial endpoint is freshly resampled from the
    prior and is not paired with the trajectory that generated X_T.
    """
    key_idx, key_x0, key_t, key_bridge = jax.random.split(key, 4)
    valid_count = jnp.maximum(valid_count, jnp.asarray(1, dtype=jnp.int32))
    idx = jax.random.randint(key_idx, (batch_size,), minval=0, maxval=valid_count)
    # BMS uses the independent coupling P_0^{u_i} ⊗ P_T^{u_i}.
    # The replay buffer stores terminal samples X_T ~ P_T^{u_i}; X_0 is drawn
    # independently from the prior for every Markovianization mini-batch.
    del buffer_x0
    xT = buffer_xT[idx]
    xT = safe_array(xT, state_clip)
    xT = jax.lax.stop_gradient(xT)
    x0 = jnp.sqrt(prior_var) * jax.random.normal(key_x0, (batch_size, target_means.shape[1]))

    t = jax.random.uniform(key_t, (batch_size,), minval=t_eps, maxval=1.0 - t_eps)
    xt = sample_brownian_bridge(x0, xT, t, key_bridge, sigma)

    xi = bms_independent_target_control(x0, xT, xt, t, sigma, prior_var, target_means, target_var)
    xi = clip_vector_norm(safe_array(xi, state_clip), xi_clip)
    xi = jax.lax.stop_gradient(xi)
    u_ref = state.apply_fn({"params": ref_params}, xt, t, sigma)
    u_ref = clip_vector_norm(safe_array(u_ref, state_clip), control_clip)
    u_ref = jax.lax.stop_gradient(u_ref)

    def loss_fn(params):
        u_pred = state.apply_fn({"params": params}, xt, t, sigma)
        u_pred = clip_vector_norm(safe_array(u_pred, state_clip), control_clip)
        drift_mse = 0.5 * jnp.mean(jnp.sum((u_pred - xi)**2, axis=-1))
        damping = 0.5 * eta * jnp.mean(jnp.sum((u_pred - u_ref)**2, axis=-1))
        total = drift_mse + damping
        return total, {"loss": total, "drift_mse": drift_mse, "damping": damping}

    (loss, metrics), grads = jax.value_and_grad(loss_fn, has_aux=True)(state.params)
    state, update_finite = apply_gradients_if_finite(state, grads, loss)
    metrics = safe_metric_dict(metrics)
    metrics["update_finite"] = update_finite
    return state, metrics


